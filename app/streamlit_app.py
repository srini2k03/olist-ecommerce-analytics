"""Olist e-commerce analytics dashboard.

Reads only the small prebuilt artefacts in app/data (regenerated by the
build-data workflow), so it starts quickly on Streamlit Community Cloud.
"""

from __future__ import annotations

import json
from pathlib import Path

import altair as alt
import pandas as pd
import streamlit as st

DATA = Path(__file__).parent / "data"
BLUE, ORANGE, AQUA = "#2a78d6", "#eb6834", "#1baf7a"
SEGMENT_COLORS = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4"]

st.set_page_config(page_title="Olist analytics", page_icon="📦", layout="wide")


@st.cache_data
def load():
    read = lambda name: pd.read_parquet(DATA / f"{name}.parquet")  # noqa: E731
    return {
        "kpis": json.loads((DATA / "kpis.json").read_text()),
        "card": json.loads((DATA / "model_card.json").read_text()),
        "monthly": read("monthly"),
        "cohort": read("cohort"),
        "delay": read("delivery_delay"),
        "sla": read("state_sla"),
        "segments": read("segments"),
        "sample": read("segment_sample"),
        "scores": read("churn_scores"),
    }


d = load()
k = d["kpis"]

st.title("Olist marketplace analytics")
st.caption(
    f"Brazilian e-commerce public dataset by Olist (CC BY-NC-SA 4.0), {k['period']}. "
    "Revenue = item price + freight of non-cancelled orders."
)

cols = st.columns(6)
cols[0].metric("GMV", f"R$ {k['gmv'] / 1e6:.1f}M")
cols[1].metric("Orders", f"{k['orders']:,}")
cols[2].metric("Customers", f"{k['customers']:,}")
cols[3].metric("Avg order value", f"R$ {k['aov']:.0f}")
cols[4].metric("Late deliveries", f"{k['late_rate']:.1%}")
cols[5].metric("Repeat customers", f"{k['repeat_rate']:.1%}")

tab_rev, tab_cohort, tab_seg, tab_delivery, tab_churn = st.tabs(
    ["Revenue trend", "Cohort retention", "Segments", "Delivery impact", "Churn-risk lookup"]
)

with tab_rev:
    m = d["monthly"].assign(month=lambda x: pd.to_datetime(x["month"]))
    base = alt.Chart(m).encode(x=alt.X("month:T", title=None))
    line = base.mark_line(color=BLUE, strokeWidth=2, point=alt.OverlayMarkDef(size=40)).encode(
        y=alt.Y("gmv:Q", title="GMV (R$)", axis=alt.Axis(format="~s")),
        tooltip=[
            alt.Tooltip("month:T", format="%b %Y"),
            alt.Tooltip("gmv:Q", title="GMV (R$)", format=",.0f"),
            alt.Tooltip("orders:Q", format=","),
            alt.Tooltip("aov:Q", title="AOV (R$)", format=",.0f"),
            alt.Tooltip("mom_growth:Q", title="MoM", format="+.1%"),
        ],
    )
    st.subheader("Monthly GMV")
    st.altair_chart(line.properties(height=320), width="stretch")
    c1, c2 = st.columns(2)
    c1.metric(
        "Last full month (Aug 2018)",
        f"R$ {k['gmv_last_month'] / 1e6:.2f}M",
        f"{k['mom_last_month']:+.1%} MoM",
    )
    c2.markdown(
        "Growth was steep through 2017 (Black Friday, Nov 2017, is the peak) and "
        "**flattened in 2018**. Order value is stable, so growth has come from more orders, "
        "not bigger baskets."
    )
    with st.expander("Table"):
        st.dataframe(m, hide_index=True, width="stretch")

with tab_cohort:
    c = d["cohort"].query("months_since_first <= 12").copy()
    c["retention_pct"] = c["retention"] * 100
    heat = (
        alt.Chart(c.query("months_since_first > 0"))
        .mark_rect(stroke="white", strokeWidth=1)
        .encode(
            x=alt.X("months_since_first:O", title="Months since first purchase"),
            y=alt.Y("cohort_month:O", title="First-purchase cohort"),
            color=alt.Color(
                "retention_pct:Q",
                title="% returning",
                scale=alt.Scale(scheme="blues", domain=[0, 0.8]),
            ),
            tooltip=[
                "cohort_month",
                "months_since_first",
                alt.Tooltip("retention_pct:Q", title="% of cohort", format=".2f"),
                alt.Tooltip("active_customers:Q", title="customers"),
                alt.Tooltip("cohort_size:Q", title="cohort size", format=","),
            ],
        )
        .properties(height=480)
    )
    st.subheader("Share of each cohort ordering again, by month")
    st.altair_chart(heat, width="stretch")
    m1 = c.query("months_since_first == 1")["retention"].mean()
    st.info(
        f"Average month-1 retention is **{m1:.2%}**: fewer than 1 in 200 new customers order "
        "again the next month. Olist growth is almost entirely acquisition-driven."
    )

with tab_seg:
    seg = d["segments"]
    st.subheader("RFM + K-Means segments (k = 5)")
    long = seg.melt(
        id_vars="segment", value_vars=["customer_share", "revenue_share"], var_name="measure"
    )
    long["measure"] = long["measure"].map(
        {"customer_share": "% of customers", "revenue_share": "% of revenue"}
    )
    bars = (
        alt.Chart(long)
        .mark_bar(cornerRadiusEnd=3)
        .encode(
            y=alt.Y("segment:N", sort=list(seg["segment"]), title=None),
            yOffset="measure:N",
            x=alt.X("value:Q", title=None, axis=alt.Axis(format="%")),
            color=alt.Color(
                "measure:N", scale=alt.Scale(range=[BLUE, ORANGE]), legend=alt.Legend(title=None)
            ),
            tooltip=["segment", "measure", alt.Tooltip("value:Q", format=".1%")],
        )
        .properties(height=300)
    )
    st.altair_chart(bars, width="stretch")
    show = seg[
        [
            "segment",
            "customers",
            "customer_share",
            "revenue_share",
            "recency_days",
            "frequency",
            "monetary",
            "avg_review",
            "action",
        ]
    ]
    st.dataframe(
        show.style.format(
            {
                "customer_share": "{:.1%}",
                "revenue_share": "{:.1%}",
                "recency_days": "{:.0f}",
                "frequency": "{:.2f}",
                "monetary": "R$ {:,.0f}",
                "avg_review": "{:.2f}",
            }
        ),
        hide_index=True,
        width="stretch",
    )
    pick = st.selectbox("Explore a segment", list(seg["segment"]))
    smp = d["sample"].assign(highlight=lambda x: x["segment"] == pick)
    scatter = (
        alt.Chart(smp)
        .mark_circle(size=18)
        .encode(
            x=alt.X("recency_days:Q", title="Days since last order"),
            y=alt.Y("monetary:Q", title="Lifetime spend (R$, log)", scale=alt.Scale(type="log")),
            color=alt.condition("datum.highlight", alt.value(ORANGE), alt.value("#c9c8c3")),
            opacity=alt.condition("datum.highlight", alt.value(0.9), alt.value(0.35)),
            tooltip=[
                "segment",
                "recency_days",
                "frequency",
                alt.Tooltip("monetary:Q", format=",.0f"),
            ],
        )
        .properties(height=320, title=f"{pick} (orange) within a 4,000-customer sample")
    )
    st.altair_chart(scatter, width="stretch")
    st.markdown(f"**Action for {pick}:** {seg.set_index('segment').loc[pick, 'action']}")

with tab_delivery:
    dl = d["delay"].copy()
    dl["status"] = dl["bucket_order"].map(lambda b: "late" if b >= 4 else "on time / early")
    st.subheader("Review score by delivery delay vs promised date")
    chart = (
        alt.Chart(dl)
        .mark_bar(cornerRadiusEnd=3, size=38)
        .encode(
            x=alt.X("delay_bucket:N", sort=list(dl["delay_bucket"]), title=None),
            y=alt.Y("avg_review:Q", title="Mean review (1-5)", scale=alt.Scale(domain=[0, 5])),
            color=alt.Color(
                "status:N", scale=alt.Scale(range=[ORANGE, BLUE]), legend=alt.Legend(title=None)
            ),
            tooltip=[
                "delay_bucket",
                alt.Tooltip("orders:Q", format=","),
                alt.Tooltip("avg_review:Q", format=".2f"),
                alt.Tooltip("share_1_star:Q", title="1-star share", format=".0%"),
            ],
        )
        .properties(height=300)
    )
    st.altair_chart(chart, width="stretch")
    on_time = dl.query("bucket_order <= 3")
    late = dl.query("bucket_order >= 5")
    wavg = lambda df: (df.avg_review * df.orders).sum() / df.orders.sum()  # noqa: E731
    st.warning(
        f"On-time orders average **{wavg(on_time):.2f}★**; "
        f"orders 4+ days late average **{wavg(late):.2f}★**. "
        "In notebook 02 an ordinal regression with category and state controls keeps the effect "
        "(odds ratio ≈ 0.07 for a higher score)."
    )
    sla = d["sla"].sort_values("late_rate", ascending=False)
    st.subheader("Late-delivery rate by customer state")
    st.altair_chart(
        alt.Chart(sla)
        .mark_bar(color=BLUE, cornerRadiusEnd=3)
        .encode(
            y=alt.Y("customer_state:N", sort="-x", title=None),
            x=alt.X("late_rate:Q", title="Late rate", axis=alt.Axis(format="%")),
            tooltip=[
                "customer_state",
                alt.Tooltip("orders:Q", format=","),
                alt.Tooltip("late_rate:Q", format=".1%"),
                alt.Tooltip("avg_delivery_days:Q", title="avg delivery days", format=".1f"),
                alt.Tooltip("avg_review:Q", format=".2f"),
            ],
        )
        .properties(height=480),
        width="stretch",
    )

with tab_churn:
    card = d["card"]
    tm = card["test_metrics"]
    st.subheader("Who is likely to buy again in the next 180 days?")
    st.caption(
        f"LightGBM scored as of {card['scoring_date']} on point-in-time features. Held-out test "
        f"(cutoff {card['eval_test_cutoff']}, {card['test_rows']:,} customers): ROC-AUC "
        f"{tm['roc_auc']:.3f}, PR-AUC {tm['pr_auc']:.3f} vs base rate {tm['base_rate']:.2%}; "
        f"top 10% captures {tm['capture_top10']:.1%} of repeat buyers. "
        "Signal is weak (about 1% of customers repeat in 180 days): "
        "use it to prioritise cheap actions."
    )
    scores = d["scores"]
    examples = {
        "Most likely to return": scores.nlargest(1, "p_repeat_180d").customer_unique_id.iloc[0],
        "Median customer": scores.sort_values("p_repeat_180d")
        .iloc[len(scores) // 2]
        .customer_unique_id,
        "Least likely to return": scores.nsmallest(1, "p_repeat_180d").customer_unique_id.iloc[0],
    }
    ex = st.radio("Example customers", list(examples), horizontal=True)
    cid = st.text_input("customer_unique_id", value=examples[ex]).strip().lower()
    row = scores[scores.customer_unique_id == cid]
    if row.empty:
        st.error("Customer id not found. Use a customer_unique_id from the Olist customers table.")
    else:
        r = row.iloc[0]
        c1, c2, c3, c4 = st.columns(4)
        c1.metric(
            "P(repeat in 180 days)",
            f"{r.p_repeat_180d:.2%}",
            f"{r.p_repeat_180d / tm['base_rate']:.1f}x base rate",
            delta_color="off",
        )
        c2.metric("Churn risk", f"{r.churn_risk:.1%}")
        c3.metric(
            "Repeat decile",
            f"{int(r.repeat_decile)} of 10",
            "1 = most likely to return",
            delta_color="off",
        )
        c4.metric("Segment", r.segment)
        st.markdown(
            f"**Profile:** {int(r.orders)} order(s), R$ {r.total_spend:,.2f} spent, last order "
            f"{int(r.recency_days)} days before {card['scoring_date']}, state {r.customer_state}, "
            f"last category `{r.last_category}`."
        )
        st.markdown("**Why (top SHAP contributions):**")
        for reason in r.reasons.split("; "):
            st.markdown(f"- {reason}")
    with st.expander("Score distribution by decile"):
        dec = scores.groupby("repeat_decile").agg(
            customers=("customer_unique_id", "size"), mean_p=("p_repeat_180d", "mean")
        )
        st.dataframe(dec.style.format({"mean_p": "{:.2%}"}), width="stretch")

st.divider()
st.caption(
    "Code: MIT. Data: Olist, CC BY-NC-SA 4.0 (non-commercial). Built from the pinned public "
    "dataset; see the repository README for methods and caveats."
)
