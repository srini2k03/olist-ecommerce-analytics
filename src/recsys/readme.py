"""Generate the recommender section of README.md from ``results/recsys/``.

``python -m recsys readme`` rewrites the text between the markers below;
``--check`` exits non-zero when the README is out of date. Only results whose
``data`` field is ``"real"`` are shown; until they exist the section says the
real-data run is pending.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from recsys import config
from recsys.evaluate.report import (
    STAGE_LABELS,
    ab_section,
    ablation_table,
    coldstart_section,
    stage_table,
)

START = "<!-- recsys:start (generated by `python -m recsys readme`; do not edit by hand) -->"
END = "<!-- recsys:end -->"
README = config.REPO_ROOT / "README.md"
SQL_RESULTS = config.REPO_ROOT / "results" / "sql"

ARCHITECTURE = """```mermaid
flowchart LR
    A[H&M CSVs<br/>Kaggle API] --> B[Typed parquet<br/>+ SHA-256 manifest]
    B --> C[Subset<br/>last 16 weeks, 25% of customers]
    C --> D[Week-based split<br/>train / validation / test<br/>+ leakage checks]
    D --> E1[Two-tower retrieval<br/>PyTorch + FAISS HNSW]
    D --> E2[Co-occurrence,<br/>repurchase,<br/>age popularity]
    E1 --> F[Candidate union<br/>+ point-in-time features]
    E2 --> F
    F --> G[LightGBM LambdaRank]
    D --> H[Cold start<br/>blend / attribute-only items]
    G --> I[FastAPI service<br/>Docker]
    H --> I
    I --> J[Streamlit demo]
```"""


def _real(path: Path) -> dict | None:
    if not path.exists():
        return None
    data = json.loads(path.read_text())
    return data if data.get("data") == "real" else None


def olist_numbers(sql_dir: Path = SQL_RESULTS) -> dict[str, float]:
    repeat = pd.read_csv(sql_dir / "10_repeat_purchase_rate.csv").set_index("cohort_quarter")
    basket = pd.read_csv(sql_dir / "11_basket_size.csv").set_index("basket_size")
    return {
        "customers": int(repeat.loc["All", "customers"]),
        "repeat_customers": int(repeat.loc["All", "repeat_customers"]),
        "repeat_rate": float(repeat.loc["All", "repeat_rate"]),
        "single_item_share": float(basket.loc["1", "order_share"]),
        "orders": int(basket["orders"].sum()),
    }


def render(results_dir: Path = config.RESULTS_DIR, sql_dir: Path = SQL_RESULTS) -> str:
    report = _real(results_dir / "report.json")
    latency = _real(results_dir / "serving_latency.json")
    o = olist_numbers(sql_dir)
    lines = [
        START,
        "## Fashion recommender (H&M data)",
        "",
        "A two-stage recommender (candidate retrieval, then ranking) built on the "
        "[H&M Personalized Fashion Recommendations](https://www.kaggle.com/competitions/"
        "h-and-m-personalized-fashion-recommendations) data, in `src/recsys/`. "
        "Design notes: [docs/recsys.md](docs/recsys.md).",
        "",
        "**Why not Olist?** Collaborative filtering needs customers who buy repeatedly. In "
        f"Olist only **{o['repeat_rate']:.2%}** of {o['customers']:,} customers ever place a "
        "second order (`results/sql/10_repeat_purchase_rate.csv`) and "
        f"**{o['single_item_share']:.0%}** of {o['orders']:,} orders contain a single item "
        "(`results/sql/11_basket_size.csv`), so a "
        "user-item matrix would be almost empty.",
        "",
        ARCHITECTURE,
        "",
    ]
    if report is None:
        lines += [
            "**Status: pending.** The pipeline, models, API and demo are built and tested on a "
            "synthetic H&M-shaped dataset only; no real-data result exists yet, so this section "
            "has no numbers. Pending: add the Kaggle key and run recsys-train (add the "
            "`KAGGLE_USERNAME` and `KAGGLE_KEY` repository secrets for an account that has "
            "accepted the competition rules, then copy `.github/recsys-request.example.json` to "
            "`.github/recsys-request.json` and push it to `main`, or start the *Recsys train* "
            "workflow by hand). The workflow then commits `results/recsys/` and regenerates this "
            "section.",
            "",
            "| Stage | Recall@12 | Recall@50 | NDCG@12 | MAP@12 | HitRate@12 | Coverage | "
            "Popularity bias |",
            "|---|---|---|---|---|---|---|---|",
            *[
                f"| {label} | pending | pending | pending | pending | pending | pending | pending |"
                for label in STAGE_LABELS.values()
            ],
            "",
            "Feature ablation: pending. Cold-start results: pending. A/B recommendation: pending. "
            "p95 serving latency: pending.",
            "",
        ]
    else:
        b = report["boundaries"]
        lines += [
            f"Results on the real data, test week {b['test_start']} to {b['test_end']} "
            f"(exclusive), {report['eval_users']:,} customers with a purchase; 95% bootstrap CIs "
            f"over customers. Full report: [results/recsys/report.md](results/recsys/report.md).",
            "",
            "### All stages",
            "",
            stage_table(report),
            "",
            "### Ranker feature ablation (validation)",
            "",
            ablation_table(report.get("ranking")),
            "",
            "### Cold start",
            "",
            coldstart_section(report.get("coldstart")),
            "",
            "### Simulated A/B test",
            "",
            ab_section(report.get("ab_test")),
            "",
        ]
        if latency:
            lines += [
                f"**Serving latency** ({latency['mode'].replace('_', ' ')}, "
                f"{latency['requests']:,} requests, k = {latency['k']}): "
                f"p50 {latency['p50_ms']:.1f} ms, "
                f"**p95 {latency['p95_ms']:.1f} ms**, p99 {latency['p99_ms']:.1f} ms.",
                "",
            ]
    lines += [
        "**What is built:** typed data pipeline with checksums; week-based split with leakage "
        "tests; four baselines; a PyTorch two-tower model (logQ-corrected in-batch negatives) "
        "with exact and HNSW FAISS indexes; a LightGBM LambdaRank ranker over a multi-source "
        "candidate union with point-in-time features and a feature-group ablation; cold-start "
        "paths for new customers and new articles; a test-week report with paired bootstrap "
        "differences; a simulated A/B test reusing `olist.stats.abtest`; a FastAPI service "
        "(`docker/recsys.Dockerfile`), a latency benchmark and a Streamlit demo "
        "(`app_recsys/`).",
        "",
        "**Limitations:** offline metrics on one test week; a 25% customer sample of the last 16 "
        "weeks rather than the full two years; HitRate@12 used as the conversion proxy in the "
        "simulated A/B test, with an assumed offline-to-online shrinkage; no image or text "
        "features; the serving bundle is a static snapshot as of the test week.",
        END,
    ]
    return "\n".join(lines)


def update(readme: Path = README, results_dir: Path = config.RESULTS_DIR) -> bool:
    """Rewrite the section in place. Returns True if the file changed."""
    text = readme.read_text()
    if START not in text or END not in text:
        raise ValueError(f"{readme} has no recsys markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new = head + render(results_dir) + tail
    if new == text:
        return False
    readme.write_text(new)
    return True


def is_current(readme: Path = README, results_dir: Path = config.RESULTS_DIR) -> bool:
    text = readme.read_text()
    return START in text and render(results_dir) in text
