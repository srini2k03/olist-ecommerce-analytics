"""Generate docs/data_dictionary.md, docs/metrics.md and docs/sql.md from their sources.

    python scripts/build_docs.py [--warehouse data/olist.duckdb] [--check]

Sources: olist.schema (raw tables), the SQL model headers (staging/marts), column types from
the warehouse, sql/marts/columns.yml (column descriptions), metrics/metrics.yml and the
analytics query headers. --check fails if a committed file is out of date (used in CI).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from olist.config import DOCS_DIR, DQ_DIR, METRICS_SPEC, SQL_DIR, WAREHOUSE_PATH  # noqa: E402
from olist.metrics import load_spec, metric_specs  # noqa: E402
from olist.pipeline.models import build_order, list_models  # noqa: E402
from olist.schema import TABLES  # noqa: E402
from olist.sql_runner import DOMAINS, list_queries  # noqa: E402

HEADER = "<!-- Generated by scripts/build_docs.py; do not edit by hand. -->\n\n"
RAW_NOTES = {
    "customers": "One row per order-level customer_id; customer_unique_id is the person.",
    "geolocation": "Many rows per zip prefix (1M rows for 19k prefixes), some outside Brazil.",
    "order_items": "One row per unit sold; price and freight per item.",
    "order_payments": "One row per payment of an order (several for split payments).",
    "order_reviews": "Satisfaction surveys; review_id is shared across orders in 789 cases.",
    "orders": "One row per order with status and the purchase/delivery timestamps.",
    "products": "Product attributes; the source misspells 'length' as 'lenght'.",
    "sellers": "One row per seller with location.",
    "category_translation": "Portuguese -> English category names (2 categories missing).",
}


def _columns_doc() -> dict:
    return yaml.safe_load((SQL_DIR / "marts" / "columns.yml").read_text())


def column_description(doc: dict, table: str, column: str) -> str | None:
    return (doc["tables"].get(table) or {}).get(column) or doc["common"].get(column)


def mart_columns(warehouse: Path) -> dict[str, list[tuple[str, str]]]:
    import duckdb

    con = duckdb.connect(str(warehouse), read_only=True)
    try:
        out = {}
        for m in list_models():
            rows = con.execute(f"DESCRIBE {m.name}").fetchall()
            out[m.name] = [(r[0], r[1]) for r in rows]
        return out
    finally:
        con.close()


def data_dictionary(warehouse: Path) -> str:
    rows = {}
    report = DQ_DIR / "report.json"
    if report.exists():
        counts = json.loads(report.read_text())["row_counts"]
        rows = {**counts["raw"], **counts["staging"], **counts["marts"]}
    doc = _columns_doc()
    types = mart_columns(warehouse)
    out = [
        HEADER,
        "# Data dictionary\n\n",
        "Layers: **raw** (the 9 CSVs loaded with explicit types) → **staging** (`stg_*`, "
        "cleaned and normalised) → **marts** (`fct_*`, `dim_*`, what analytics read). Row "
        "counts are from the real data (results/data_quality/report.json). See "
        "[architecture.md](architecture.md) for the ER diagram and the pipeline.\n",
    ]
    out.append("\n## Raw layer\n")
    for t in TABLES:
        out.append(f"\n### `{t.name}` ({rows.get(t.name, 0):,} rows)\n\n")
        out.append(f"Source `{t.csv}`. {RAW_NOTES.get(t.name, '')}\n\n")
        out.append("| Column | Type |\n|---|---|\n")
        out += [f"| `{c}` | {typ} |\n" for c, typ in t.columns]
    for layer in ("staging", "marts"):
        out.append(f"\n## {layer.capitalize()} layer\n")
        for m in (x for x in build_order(list_models()) if x.layer == layer):
            h = m.header
            out.append(f"\n### `{m.name}` ({rows.get(m.name, 0):,} rows)\n\n")
            out.append(
                f"**Grain:** {h.get('Grain', '')}  \n**Purpose:** {h.get('Purpose', '')}  \n"
            )
            out.append(f"**Depends on:** {', '.join(f'`{d}`' for d in m.depends_on)}\n\n")
            if h.get("Transformations"):
                out.append(f"{h['Transformations']}\n\n")
            if layer == "marts":
                out.append("| Column | Type | Description |\n|---|---|---|\n")
                for c, typ in types[m.name]:
                    out.append(f"| `{c}` | {typ} | {column_description(doc, m.name, c) or ''} |\n")
            else:
                out.append("Columns: " + ", ".join(f"`{c}`" for c, _ in types[m.name]) + "\n")
    return "".join(out)


def metrics_doc() -> str:
    spec = load_spec(METRICS_SPEC)
    specs = metric_specs(spec)
    out = [
        HEADER,
        "# Metric definitions\n\n",
        "Source of truth: [`metrics/metrics.yml`](../metrics/metrics.yml). The SQL below is "
        "what the cross-check test runs on the marts; `src/olist/metrics.py` implements the "
        "same definitions in pandas for the dashboard, and the test requires both to agree."
        "\n\n## Revenue is not payment value is not GMV\n\n"
        "| Quantity | Formula | What it is | Observed? |\n|---|---|---|---|\n"
        "| Item revenue | SUM(price) | merchandise value paid to sellers | yes |\n"
        "| Freight | SUM(freight_value) | shipping charged to customers, passed to carriers "
        "| yes |\n"
        "| GMV | item revenue + freight | gross merchandise value of valid orders | yes |\n"
        "| Payment value | SUM(payment_value) | cash charged; includes instalment interest "
        "and vouchers | yes |\n"
        "| Marketplace revenue (estimate) | take rate x item revenue | Olist's own revenue "
        "| **no**: assumed take rate |\n"
        "| Contribution (estimate) | marketplace revenue - payment cost (- subsidies) | a "
        "profit proxy | **no**: assumptions only |\n\n"
        "## Assumptions\n\n| Name | Value | Label | Note |\n|---|---|---|---|\n",
    ]
    for name, a in spec["assumptions"].items():
        out.append(f"| `{name}` | {a['value']} | {a['label']} | {' '.join(a['note'].split())} |\n")
    for domain in sorted({s.domain for s in specs.values()}):
        out.append(f"\n## {domain.capitalize()}\n\n| Metric | Unit | Kind | Definition | SQL |\n")
        out.append("|---|---|---|---|---|\n")
        for s in specs.values():
            if s.domain != domain:
                continue
            sql = s.sql.get("query") or (
                f"SELECT {s.sql['expr']} FROM {s.sql['table']}"
                + (f" WHERE {s.sql['where']}" if s.sql.get("where") else "")
            )
            sql = " ".join(sql.split()).replace("|", "\\|")
            definition = s.definition + (f" *Caveat: {s.caveats}*" if s.caveats else "")
            out.append(
                f"| **{s.label}** (`{s.name}`) | {s.unit} | {s.kind} | {definition} | `{sql}` |\n"
            )
    return "".join(out)


def sql_doc() -> str:
    out = [
        HEADER,
        "# SQL library\n\n",
        "Analytics queries live in `sql/analytics/<domain>/NN_name.sql` and read only the "
        "marts (a test enforces it). Each starts with a header giving the business question, "
        "method, expected output and dialect notes. Every query runs unchanged on DuckDB and "
        "Postgres; CI requires identical results on the real data. Snapshots: "
        "[`results/sql/`](../results/sql).\n\n"
        "Portability rules: day differences as `CAST(a AS DATE) - CAST(b AS DATE)`; months "
        "via `CAST(date_trunc('month', ts) AS DATE)`; `EXTRACT` cast to `INTEGER`; no "
        "`ROUND(double, n)`; `LOWER(...) LIKE` instead of `ILIKE`; deterministic `ORDER BY` "
        "(float ties sort differently across engines); anti-joins as `LEFT JOIN ... IS NULL` "
        "(Postgres runs `NOT EXISTS` inside `CASE` row by row).\n",
    ]
    for domain in DOMAINS:
        out.append(f"\n## {domain.capitalize()}\n")
        for q in (q for q in list_queries() if q.domain == domain):
            h = q.header
            out.append(
                f"\n### {q.name} ([sql](../sql/analytics/{domain}/{q.name}.sql), "
                f"[result](../results/sql/{q.name}.csv))\n\n"
            )
            for key in ("Business question", "Method", "Expected output", "Dialect notes"):
                if h.get(key):
                    out.append(f"- **{key}:** {h[key]}\n")
    out.append("\n## Staging and marts models\n\n| Model | Layer | Grain |\n|---|---|---|\n")
    for m in build_order(list_models()):
        out.append(f"| `{m.name}` | {m.layer} | {m.header.get('Grain', '')} |\n")
    return "".join(out)


def generate(warehouse: Path) -> dict[str, str]:
    return {
        "data_dictionary.md": data_dictionary(warehouse),
        "metrics.md": metrics_doc(),
        "sql.md": sql_doc(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--warehouse", type=Path, default=WAREHOUSE_PATH)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    DOCS_DIR.mkdir(exist_ok=True)
    stale = []
    for name, text in generate(args.warehouse).items():
        path = DOCS_DIR / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
            print("wrote", path)
    if stale:
        print("out of date (run python scripts/build_docs.py):", stale)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
